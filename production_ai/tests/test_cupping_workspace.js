const assert = require("node:assert/strict");
const vm = require("node:vm");
const {runStartup} = require("./test_client_startup");
const roasts = ["검댕이","노랭이"].flatMap(roaster => [1,2,3].map(n=>({id:`${roaster}${n}`,entryType:"roasting",roastDate:"2026-11-18",blend:"올드독",batch:`#${n}`,roastData:{roaster,wholeColor:"48.5",groundColor:"55.2"}})));
const cup = {id:"own",entryType:"cupping",roastDate:"2026-11-18",blend:"올드독",batch:"#1",sourceIds:["검댕이1"],createdBy:"test-admin",note:"OK",verdict:"pass",roastData:{roaster:"검댕이"}};
const state = runStartup({mira_blend_qc_entries_v1:[...roasts,cup]});
const {context,listeners,elements,requests}=state;
const read = code=>JSON.parse(vm.runInContext(`JSON.stringify(${code})`,context));
vm.runInContext('selectedCuppingDate="2026-11-18";renderCuppingBatchPicker()',context);
assert.equal(elements.get("#cuppingEvaluationProgress").textContent,"내 평가 1 / 6");
assert.ok(elements.get("#cuppingBatchList").innerHTML.includes("홀빈 <b>48.5</b>"));
assert.ok(elements.get("#cuppingBatchList").innerHTML.includes("노랭이 · 올드독"));
assert.ok(!elements.get("#cuppingBatchList").innerHTML.includes('data-cupping-roast-entry="검댕이1"'));
listeners.get("#cuppingSelectAllButton:click")[0]();
assert.equal(read("selectedCuppingBatchIds.size"),5);
assert.equal(elements.get("#cuppingSaveCount").textContent,"5개 선택");
assert.equal(elements.get("#cuppingSaveButton").disabled,false);
assert.ok(elements.get("#cuppingSelectedSummary").textContent.includes("노랭이"));
listeners.get("#cuppingCompletedButton:click")[0]();
assert.ok(elements.get("#cuppingBatchList").innerHTML.includes("completed"));
assert.ok(!elements.get("#cuppingBatchList").innerHTML.includes("data-cupping-roast-entry"),"completed records are read-only in this picker");
assert.equal(read("selectedCuppingBatchIds.size"),5,"switching views preserves pending selection");
listeners.get("#cuppingFooterClearButton:click")[0]();
assert.equal(read("selectedCuppingBatchIds.size"),0);
assert.equal(elements.get("#cuppingSaveButton").disabled,true);
listeners.get("#cuppingPendingButton:click")[0]();
listeners.get("#cuppingBatchForm:click")[0]({target:{closest:()=>({dataset:{cuppingVerdict:"hold"}})}});
assert.equal(read("cuppingBatchFields.verdict.value"),"hold");
listeners.get("#cuppingPickerDateInput:change")[0]({target:{value:"2026-11-19"}});
assert.equal(read("selectedCuppingDate"),"2026-11-19");
assert.equal(read("selectedCuppingBatchIds.size"),0);
assert.equal(elements.get("#cuppingSaveButton").disabled,true);
assert.equal(requests.length,1,"selection, filters and verdict controls never persist data");
console.log("Cupping workspace: own progress, roaster separation, color values, bulk selection/clear, completed view, verdict control and date reset passed.");
