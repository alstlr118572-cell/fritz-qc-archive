const assert = require("node:assert/strict");
const vm = require("node:vm");
const {runStartup} = require("./test_client_startup");
const sample={id:"v",entryType:"visit",visitDate:"2026-11-18",sourceFileName:"원본.pdf",visitData:{store:"테스트 상호",coffee:"올드독, 잘되어가시나, 디카페인",basket:"IMS 20g",flowPressure:"9bar / 좌:305.0 중:999 우:295.0",beverageQuality:"올드독 5/21 로스팅 1번, 올드독 6/30 #1\n잘되어 가시나 11/2 #10\n디카페인 10/10 #2",extractions:[{blend:"올드독",dose:"18g",yield:"36g",time:"27s",tds:"10%"},{blend:"잘되어 가시나",dose:"20",yield:"40",time:"30",tds:"9"},{blend:"디카페인",dose:"19",yield:"38",time:"29",tds:"8"}]}};
