assert.deepEqual(read('visitExportRoastDates("12/31 #1", "2026-01-03")'),["25.12.31."]);
assert.deepEqual(read('visitExportRoastDates("2/30 #1 TDS:9.5% 18g", "2026-11-18")'),[]);
assert.deepEqual(read('visitExportRoastDates("5월 21일 #1", "2026-11-18")'),["26.05.21."]);
assert.deepEqual(read('visitExportRoastDates("5/21 #1", "")'),[]);
context.unknown={id:"unknown",entryType:"visit",visitDate:"2026-11-18",visitData:{store:"미확인",coffee:"올드독,잘되어가시나",recipe:"Input:18g Output:36g Time:27s TDS:10%",beverageQuality:"5/21 로스팅 #1"}};
