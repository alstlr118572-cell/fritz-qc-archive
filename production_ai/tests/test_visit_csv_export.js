assert.equal(rows[1][1],"잘되어 가시나");
assert.equal(rows[1][2],"26.11.02.");
assert.equal(rows[1][7],18);
assert.equal(read('visitExportFlowClass("9bar 좌 300 우 299")'),"10g/s 이하");
assert.equal(read('visitExportFlowClass("좌300 우300")'),"10g/s 이상");
assert.equal(read('visitExportFlowClass("왼쪽 그룹:301 오른쪽 그룹:300 중:1")'),"10g/s 이상");
