assert.equal(unknown.length,2);
assert.ok(unknown.every(row=>row[2]===""&&row[3]===""&&row[11]===""),"do not share unidentified dates/recipes across coffees or invent filenames");
context.single={...context.unknown,visitData:{...context.unknown.visitData,coffee:"올드독"}};
const single=read("buildVisitExportRows([single])");
assert.equal(single[0][2],"26.05.21.");
